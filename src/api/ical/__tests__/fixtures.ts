const crlf = (s: string) => s.replace(/\r\n/g, '\n').trim().split('\n').join('\r\n') + '\r\n'

export function obj(
  data: string,
  url = 'https://daisycal.home/dav/daisy/work/x.ics',
): CalendarObject {
  return {
    url,
    collectionUrl: url.slice(0, url.lastIndexOf('/') + 1),
    etag: '"e1"',
    data: crlf(data),
  }
}

